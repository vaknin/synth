//! Internal macro definitions for ADC pin type erasure.
//!
//! This module generates type-erased ADC pin enums and setup helpers,
//! enabling heterogeneous GPIO types to be stored in arrays without heap allocation.

/// Generate type-erased ADC pin enum and setup infrastructure.
///
/// This macro creates:
/// - Type aliases for each pin (Pin1, Pin2, etc.)
/// - AnyAdcPin enum with variants for each GPIO type
/// - read_blocking() implementation that delegates to typed ADC calls
/// - setup_adc!() macro for clean initialization
///
/// # Example
/// ```rust
/// adc_pins! {
///     1: GPIO1,
///     2: GPIO2,
///     3: GPIO3,
///     4: GPIO4,
/// }
/// ```
///
/// This generates an enum with 4 variants and returns `[AnyAdcPin; 4]` from setup.
#[macro_export]
macro_rules! adc_pins {
    ($($num:tt: $gpio:ty),+ $(,)?) => {
        $crate::paste::paste! {
            // Generate type aliases: Pin1, Pin2, etc.
            $(
                type [<Pin $num>] = $crate::hardware::PotPin<$gpio>;
            )+

            /// Type-erased ADC pin - enables storing heterogeneous GPIO pins in arrays.
            ///
            /// Each variant wraps a specific GPIO type. The enum uses static dispatch
            /// (match statement) which compiles to zero-cost abstraction - identical
            /// to calling ADC methods directly on typed pins.
            pub enum AnyAdcPin {
                $([<Pin $num>]([<Pin $num>]),)+
            }

            impl AnyAdcPin {
                /// Read ADC value from this pin using blocking I/O.
                ///
                /// Delegates to the typed ADC read_blocking() method based on
                /// the pin variant. The match is optimized away in release builds.
                #[inline]
                pub fn read_blocking(&mut self, adc: &mut $crate::hardware::Adc1) -> u16 {
                    match self {
                        $(Self::[<Pin $num>](p) => adc.read_blocking(p),)+
                    }
                }
            }

            /// Initialize ADC with potentiometer pins (generated function).
            ///
            /// Returns (AdcBus, [AnyAdcPin; N]) where N matches the pin count.
            ///
            /// This is a regular function generated by the macro, with explicit
            /// parameters for each GPIO pin.
            pub fn setup_adc(
                adc1: esp_hal::peripherals::ADC1<'static>,
                $(
                    [<gpio $num>]: $gpio,
                )+
            ) -> (AdcBus, [AnyAdcPin; $crate::count_tokens!($($num)+)]) {
                use esp_hal::analog::adc::{Adc, AdcConfig, AdcCalCurve, Attenuation};

                let mut cfg = AdcConfig::new();
                let pins = [
                    $(
                        AnyAdcPin::[<Pin $num>](
                            cfg.enable_pin_with_cal::<_, AdcCalCurve<_>>([<gpio $num>], Attenuation::_11dB)
                        ),
                    )+
                ];
                (AdcBus { adc: Adc::new(adc1, cfg) }, pins)
            }
        }
    };
}

/// Helper macro to count tokens (for array size inference).
#[doc(hidden)]
#[macro_export]
macro_rules! count_tokens {
    () => { 0 };
    ($one:tt $($rest:tt)*) => { 1 + $crate::count_tokens!($($rest)*) };
}
